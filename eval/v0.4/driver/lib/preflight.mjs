import { spawnSync } from 'node:child_process'
import { access, readFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { sha256 } from '../../lib/canonical.mjs'
import { driverSourceDigest } from '../../lib/integrity.mjs'
import { resolveRuntimeArtifact } from './evocode.mjs'
import { assertExactCheckout } from './runtime.mjs'

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..', '..', '..')

async function exists(path) {
  try {
    await access(path)
    return true
  } catch {
    return false
  }
}

function executable(command, args = ['--version']) {
  const result = spawnSync(command, args, { encoding: 'utf8' })
  return result.status === 0
}

export async function preflight(spec) {
  const checks = []
  const add = (name, ok, detail) => checks.push({ name, ok, detail })
  for (const [name, expected] of Object.entries(spec.sourceCommits)) {
    const root = spec.benchmarkRoots[name]
    if (!root) {
      add(`${name}-checkout`, false, `${name} root is not configured`)
      continue
    }
    try {
      assertExactCheckout(root, expected, name)
      add(`${name}-checkout`, true, expected)
    } catch (error) {
      add(`${name}-checkout`, false, error.message)
    }
  }
  add('node', executable(process.execPath, ['--version']), process.version)
  add('driver-source-binding', await driverSourceDigest() === spec.expectedProvenance?.driverSourceDigest, 'driver tree must match the frozen manifest')
  add('pnpm', executable('pnpm'), 'required for isolated profile and exact plugin packaging')
  add('git', executable('git'), 'required for exact source verification')
  if (spec.run.suite === 'simple' && spec.simpleTask?.language === 'Go') add('go', executable('go', ['version']), 'required by the hidden Go grader')
  if (spec.run.suite === 'simple' && spec.simpleTask?.language === 'Python') add('python3', executable('python3'), 'required by the hidden Python grader')
  if (spec.run.suite === 'simple' || spec.run.suite === 'icae') {
    const artifact = spec.runtimeArtifacts?.hostHarness
    const runtimePath = artifact?.pathEnvironmentVariable ? process.env[artifact.pathEnvironmentVariable] : undefined
    const runtimeExists = Boolean(runtimePath && await exists(resolve(runtimePath)))
    add('host-harness-runtime-path', runtimeExists, artifact?.pathEnvironmentVariable ?? 'host runtime artifact is not configured')
    if (runtimeExists) {
      add('host-harness-runtime-digest', sha256(await readFile(resolve(runtimePath))) === artifact.sha256, 'host Harness runtime must match its frozen digest')
    }
    add('host-process-isolation', process.platform === 'darwin' && executable('/usr/bin/sandbox-exec', ['-p', '(version 1) (allow default) (deny process-info*)', '/usr/bin/true']), 'host Harness requires Darwin process-info isolation')
  }
  if (spec.run.suite !== 'simple') add('docker', executable('docker'), 'required by the official benchmark grader')
  if (spec.run.suite === 'icae') {
    add('icae-hidden-asset-isolation', process.platform === 'darwin' && executable('/usr/bin/sandbox-exec', ['-p', '(version 1) (allow default) (deny process-info*) (deny network-outbound (remote tcp "*:50001") (remote tcp "*:50002") (remote tcp "*:50003"))', '/usr/bin/true']), 'frozen ICAE driver requires Darwin sandbox-exec process, read, and Oracle-port isolation')
  }
  if (spec.run.suite === 'evocode') add('uv', executable('uv'), 'required to run pinned Harbor with its frozen lockfile')
  if (spec.run.suite === 'evocode' && spec.benchmarkRoots.harbor) {
    const harbor = spawnSync('uv', ['run', '--frozen', '--offline', '--project', resolve(spec.benchmarkRoots.harbor), 'harbor', '--version'], { encoding: 'utf8' })
    add('harbor-offline-runtime', harbor.status === 0, 'pinned Harbor must start from its frozen lock without network resolution')
  }
  if (spec.run.suite === 'icae' && spec.benchmarkRoots.icae) {
    const root = resolve(spec.benchmarkRoots.icae)
    add('icae-alias-map', await exists(join(root, 'repo_alias.json')), 'generated by ICAE setup.sh')
    add('icae-prds', await exists(join(root, 'fuzzy_prds')), 'downloaded official fuzzy PRDs')
    add('icae-authoritative-tests', await exists(join(root, 'rcb_tests_repos')), 'downloaded authoritative hidden tests')
    add('icae-golden-repositories', await exists(join(root, 'realcode_repos')), 'downloaded golden source repositories')
    add('icae-language-images', await exists(join(root, 'docker_lang_official')), 'downloaded official language image tarballs')
  }
  if (spec.run.suite === 'evocode' && spec.benchmarkRoots.evocode) {
    const root = resolve(spec.benchmarkRoots.evocode)
    const task = join(root, 'data', 'EvoCodeBench', spec.run.taskLocator.harborTaskId, 'task.toml')
    add('evocode-task-assets', await exists(task), task)
    const artifactId = spec.run.arm.id === 'native' ? 'native' : spec.run.arm.id
    const artifact = spec.runtimeArtifacts?.artifacts?.[artifactId]
    add('evocode-runtime-lock', /^[0-9a-f]{64}$/.test(artifact?.sha256 ?? '') && /^[0-9a-f]{64}$/.test(artifact?.metadataDigest ?? ''), `frozen Linux runtime for ${artifactId}`)
    const runtimePath = artifact?.pathEnvironmentVariable ? process.env[artifact.pathEnvironmentVariable] : undefined
    add('evocode-runtime-path', Boolean(runtimePath && await exists(resolve(runtimePath))), artifact?.pathEnvironmentVariable ?? 'runtime artifact is not configured')
    if (runtimePath && await exists(resolve(runtimePath))) {
      try {
        const runtime = await resolveRuntimeArtifact(spec)
        add('evocode-runtime-identity', true, `${runtime.id}:${runtime.metadata.armDigest}`)
      } catch (error) {
        add('evocode-runtime-identity', false, error.message)
      }
    }
  }
  const candidate = spec.pluginCommits['v0.4.0Candidate']
  const frozen = /^[0-9a-f]{40}$/.test(candidate)
  add('candidate-frozen', frozen, 'candidate must be an exact commit before any infrastructure or statistical run')
  if (frozen) {
    const object = spawnSync('git', ['-C', repositoryRoot, 'cat-file', '-e', `${candidate}^{commit}`])
    const ancestor = spawnSync('git', ['-C', repositoryRoot, 'merge-base', '--is-ancestor', candidate, 'HEAD'])
    const status = spawnSync('git', ['-C', repositoryRoot, 'status', '--porcelain', '--untracked-files=all'], { encoding: 'utf8' })
    add(
      'candidate-checkout-clean',
      object.status === 0 && ancestor.status === 0 && status.status === 0 && status.stdout.trim() === '',
      'candidate must be an ancestor of the clean evaluation lock checkout',
    )
  }
  const runtimeDigestsFrozen = spec.runtimeArtifacts?.status === 'frozen'
    && /^[0-9a-f]{64}$/.test(spec.runtimeArtifacts?.baseImage?.digest ?? '')
    && /^[0-9a-f]{64}$/.test(spec.runtimeArtifacts?.hostHarness?.sha256 ?? '')
    && Object.values(spec.runtimeArtifacts?.artifacts ?? {}).every((artifact) => /^[0-9a-f]{64}$/.test(artifact.sha256 ?? '') && /^[0-9a-f]{64}$/.test(artifact.metadataDigest ?? ''))
  add('runtime-artifacts-frozen', runtimeDigestsFrozen, 'base image and every arm-specific Linux runtime must be content-addressed')
  add(
    'runtime-artifacts-manifest-binding',
    sha256(spec.runtimeArtifacts) === spec.expectedProvenance?.runtimeArtifactsDigest,
    'runtime artifact lock must match the frozen manifest provenance',
  )
  if (process.env.DEEPSEEK_API_KEY) {
    add('api-key-environment', true, 'configured through environment')
  } else {
    add('api-key-environment', false, 'DEEPSEEK_API_KEY is absent')
  }
  if (process.env.DEEPSEEK_BASE_URL) {
    try {
      const endpoint = new URL(process.env.DEEPSEEK_BASE_URL)
      add('endpoint', ['http:', 'https:'].includes(endpoint.protocol), `${endpoint.protocol}//${endpoint.host}`)
    } catch {
      add('endpoint', false, 'DEEPSEEK_BASE_URL is invalid')
    }
  } else {
    add('endpoint', true, 'provider default')
  }
  const blindResultPath = join(repositoryRoot, 'eval', 'router-corpus', 'blind-real-results.json')
  try {
    const blind = JSON.parse(await readFile(blindResultPath, 'utf8'))
    add('router-blind-result-binding', sha256(blind) === spec.routerBlindResultDigest, 'blind result must match the frozen manifest digest')
    add(
      'router-blind-release-gate',
      blind.releaseGatePassed === true,
      blind.releaseGatePassed === true
        ? `passed ${blind.samples} frozen real-source samples`
        : `failed: falseActivation=${blind.metrics?.simpleFalseActivationRate}, complexRecall=${blind.metrics?.complexCriticalRecall}, criticalBypasses=${blind.metrics?.outcomeCriticalBypassCount}`,
    )
  } catch (error) {
    add('router-blind-release-gate', false, `unavailable: ${error.message}`)
  }
  await readFile(new URL('../support-plugin/index.js', import.meta.url), 'utf8')
  return { ok: checks.every((check) => check.ok), checks }
}
